use super::*;

fn read_code(format: &str, source: &str) -> Result<Model> {
    if format == "bgcode" {
        parse(format,&testdata::bgcode(0,0,source.as_bytes(),source.len()))
    } else {
        parse(format,source.as_bytes())
    }
}

#[test]
fn r2_numbered_non_motion_commands_do_not_move_or_reject_the_toolpath() {
    let prefix = "G90\nM83\nG1 X10 E1 F1200\n";
    let mut failures = Vec::new();
    for command in ["M201 X500","M117 Printing"] {
        for format in ["gcode","bgcode"] {
            let source = format!("{prefix}{command}\nG1 X20 E1\n");
            let control = read_code(format,&source).unwrap();
            let numbered: String = source.lines().enumerate().map(|(i,line)| {
                let line = format!("N{} {line}",i+1);
                let checksum = line.bytes().fold(0u8,|n,b| n^b);
                format!("{line}*{checksum}\n")
            }).collect();
            let result = read_code(format,&numbered);
            match result {
                Ok(actual) => {
                    eprintln!("{format}, {command}: control segments={}, dimensions={:?}; numbered segments={}, dimensions={:?}",
                        control.segments.len(),control.facts(None).dimensions_mm,actual.segments.len(),actual.facts(None).dimensions_mm);
                    if actual.segments != control.segments { failures.push(format!("{format}: numbered {command} dispatched modal motion")); }
                }
                Err(reason) => {
                    eprintln!("{format}, {command}: control parsed; numbered result=Err({reason:?})");
                    failures.push(format!("{format}: numbered {command} rejected: {reason}"));
                }
            }
        }
    }
    assert!(failures.is_empty(),"{}",failures.join("; "));
}

#[test]
fn r2_bambu_header_exports_print_time_filament_length_and_weight() {
    let source = "; generated by BambuStudio\n; model printing time: 1h 0m 0s; total estimated time: 1h 5m 0s\n; total filament length [mm] : 1000.00, 2000.00\n; total filament weight [g] : 3.00, 6.00\nG90\nM83\nG1 X10 E1 F1200\n";
    let model = parse("gcode",source.as_bytes()).unwrap();
    let actual = model.slicer(None);
    eprintln!("Bambu header facts: {actual:?}; raw metadata: {:?}",model.metadata);
    assert_eq!((actual.print_time_s,actual.filament_mm,actual.weight_g),
        (Some(3900.),Some(3000.),Some(9.)),"available slicer facts must survive normalization");
}
