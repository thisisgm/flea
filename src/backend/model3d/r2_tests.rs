use super::*;

fn numbered(source: &str, style: usize) -> String {
    if style == 0 { return source.into() }
    source.lines().enumerate().map(|(i,line)| {
        let line = match style {
            1 => format!("N{} {line}",i+1),
            2 => format!("N{}{line}",i+1),
            _ => format!("n {} {line}",i+1),
        };
        let checksum = line.bytes().fold(0u8,|n,b| n^b);
        format!("{line}*{checksum}\n")
    }).collect()
}

fn read_code(format: &str, source: &str) -> Model {
    if format == "bgcode" { parse(format,&testdata::bgcode(0,0,source.as_bytes(),source.len())).unwrap() }
    else { parse(format,source.as_bytes()).unwrap() }
}

#[test]
fn numbered_m_commands_keep_parameters_out_of_motion_tool_and_feed_state() {
    for command in ["M201 X500 Y500 Z99 E9 F60 T2","M104 T2 S210","M117 Printing X500 T2 E9 F60","m117 ready to print"] {
        for arc in [None,Some(2),Some(3)] {
            let (prefix,movement) = if let Some(arc) = arc {
                (format!("G90\nM83\nT1\nG1 X10 F1200\nG{arc} X0 Y10 I-10 J0 E1\n"),"X-10 Y0 I0 J-10 E1\n")
            } else {
                ("G90\nM83\nT1\nG1 X10 E1 F1200\n".into(),"X20 E1\n")
            };
            for style in 0..4 {
                for format in ["gcode","bgcode"] {
                    let expected = read_code(format,&format!("{prefix}{movement}"));
                    let source = numbered(&format!("{prefix}{command}\n{movement}"),style);
                    let actual = read_code(format,&source);
                    assert_eq!(actual.segments,expected.segments,"{format}, {command}, {arc:?}, style={style}");
                    assert_eq!(actual.facts(None),expected.facts(None));
                    assert_eq!(actual.layers,expected.layers);
                }
            }
        }
    }
}

#[test]
fn numbered_m82_m83_set_extrusion_modes_before_interpreting_arguments() {
    for (absolute,relative) in [("M82","M83"),("m082","m083"),("M 82","M 83"),("M82T0","M83T0")] {
        let source = format!("G90\nM83\nT1\nG1 X10 E5 F1200\n{absolute}\nG1 X20 E6\n{relative}\nG1 X30 E2\n{absolute}\nG1 X40 E10\n");
        for style in 0..4 {
            for format in ["gcode","bgcode"] {
                let model = read_code(format,&numbered(&source,style));
                assert_eq!(model.segments.iter().map(|s| s.extrusion_mm).collect::<Vec<_>>(),[5.,1.,2.,2.],
                    "{format}, {absolute}, {relative}, style={style}");
                assert!(model.segments.iter().all(|s| s.tool == 1 && s.feed_mm_min == 1200.));
            }
        }
    }
}

#[test]
fn bambu_exporter_headers_reach_shared_facts_wire_summary_and_roundtrip() {
    for (key,time) in [
        ("model printing time","1h 0m 0s; total estimated time: 1h 5m 0s"),
        ("MODEL PRINTING TIME","01:00:00; TOTAL ESTIMATED TIME: 01:05:00"),
        ("total estimated time","1h 5m 0s"),
    ] {
        for separator in [", ","; "] {
            let length = format!("1000.00{separator}2000.00");
            let weight = format!("3.00{separator}6.00");
            let source = format!("; generated by BambuStudio\n; {key}: {time}\n; total filament length [mm] : {length}\n; total filament weight [g] : {weight}\nG90\nM83\nG1 X10 E1 F1200\n");
            for format in ["gcode","bgcode"] {
                let model = read_code(format,&source);
                let facts = model.slicer(None);
                assert_eq!((facts.print_time_s,facts.filament_mm,facts.weight_g),(Some(3900.),Some(3000.),Some(9.)));
                assert_eq!(model.metadata[key],time);
                assert_eq!(model.metadata["total filament length [mm]"],length);
                assert_eq!(model.metadata["total filament weight [g]"],weight);
                let summary = crate::jsondoc::parse(&wire::summary(&model)).unwrap();
                let plate = &summary.get("plates").unwrap().as_array().unwrap()[0];
                for container in [&summary,plate] {
                    let slicer = container.get("slicer").unwrap();
                    for (key,value) in [("print_time_s",3900.),("filament_mm",3000.),("weight_g",9.)] {
                        assert_eq!(slicer.get(key).unwrap().as_f64(),Some(value));
                    }
                }
                assert_eq!(summary.get("metadata").unwrap().get(key).unwrap().as_str(),Some(time));
                let mut bytes = Vec::new();
                wire::write(&model,&mut bytes).unwrap();
                let restored = wire::read(std::io::Cursor::new(bytes)).unwrap();
                assert_eq!(restored.slicer(None),facts);
                assert_eq!(restored.metadata,model.metadata);
            }
        }
    }
}

#[test]
fn bambu_total_time_stays_unknown_when_invalid_or_only_mentioned_in_other_metadata() {
    for header in [
        "; model printing time: 1h; total estimated time: unknown\n",
        "; note: model printing time: 1h; total estimated time: 2h\n",
    ] {
        for format in ["gcode","bgcode"] {
            let model = read_code(format,&format!("{header}G1 X10\n"));
            assert_eq!(model.slicer(None).print_time_s,None);
        }
    }
}
