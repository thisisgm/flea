pub(super) fn bgcode(compression: u16, encoding: u16, payload: &[u8], expanded: usize) -> Vec<u8> {
    let mut out = b"GCDE".to_vec();
    out.extend_from_slice(&1u32.to_le_bytes());
    out.extend_from_slice(&1u16.to_le_bytes());
    let start = out.len();
    out.extend_from_slice(&1u16.to_le_bytes());
    out.extend_from_slice(&compression.to_le_bytes());
    out.extend_from_slice(&(expanded as u32).to_le_bytes());
    if compression != 0 { out.extend_from_slice(&(payload.len() as u32).to_le_bytes()) }
    out.extend_from_slice(&encoding.to_le_bytes());
    out.extend_from_slice(payload);
    let crc = codecs::crc32(&out[start..]);
    out.extend_from_slice(&crc.to_le_bytes());
    out
}

pub(super) fn heatshrink_literal(bytes: &[u8]) -> Vec<u8> {
    let mut bits = Vec::new();
    for &byte in bytes { bits.push(1); for shift in (0..8).rev() { bits.push((byte >> shift)&1) } }
    let mut out = vec![0;bits.len().div_ceil(8)];
    for (at,bit) in bits.into_iter().enumerate() { out[at/8] |= bit << (7-at%8) }
    out
}

pub(super) fn hex(source: &str) -> Vec<u8> {
    source.as_bytes().as_chunks::<2>().0.iter().map(|p| u8::from_str_radix(std::str::from_utf8(p).unwrap(),16).unwrap()).collect()
}

pub(super) fn ply(format: &str) -> Vec<u8> {
    let mut out = format!("ply\nformat {format} 1.0\nelement vertex 3\nproperty float x\nproperty float y\nproperty float z\nproperty uchar red\nproperty uchar green\nproperty uchar blue\nelement face 1\nproperty list uchar int vertex_indices\nend_header\n").into_bytes();
    if format == "ascii" { out.extend_from_slice(b"0 0 0 255 0 0\n10 0 0 0 255 0\n0 10 0 0 0 255\n3 0 1 2\n") }
    else {
        for (point,color) in [([0f32,0.,0.],[255,0,0]),([10.,0.,0.],[0,255,0]),([0.,10.,0.],[0,0,255])] {
            for n in point { out.extend_from_slice(&if format == "binary_big_endian" { n.to_be_bytes() } else { n.to_le_bytes() }) }
            out.extend_from_slice(&color);
        }
        out.push(3);
        for n in [0u32,1,2] { out.extend_from_slice(&if format == "binary_big_endian" { n.to_be_bytes() } else { n.to_le_bytes() }) }
    }
    out
}
