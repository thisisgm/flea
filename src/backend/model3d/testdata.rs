pub(crate) fn archive(files: &[(&str,&[u8])]) -> Vec<u8> {
    let mut out = Vec::new();
    let mut central = Vec::new();
    for &(name,payload) in files {
        let offset = out.len() as u32;
        let crc = codecs::crc32(payload);
        out.extend_from_slice(b"PK\x03\x04");
        for n in [20u16,0,0,0,0] { out.extend_from_slice(&n.to_le_bytes()) }
        for n in [crc,payload.len() as u32,payload.len() as u32] { out.extend_from_slice(&n.to_le_bytes()) }
        out.extend_from_slice(&(name.len() as u16).to_le_bytes());
        out.extend_from_slice(&0u16.to_le_bytes());
        out.extend_from_slice(name.as_bytes());
        out.extend_from_slice(payload);
        central.extend_from_slice(b"PK\x01\x02");
        for n in [20u16,20,0,0,0,0] { central.extend_from_slice(&n.to_le_bytes()) }
        for n in [crc,payload.len() as u32,payload.len() as u32] { central.extend_from_slice(&n.to_le_bytes()) }
        for n in [name.len() as u16,0,0,0,0] { central.extend_from_slice(&n.to_le_bytes()) }
        central.extend_from_slice(&0u32.to_le_bytes());
        central.extend_from_slice(&offset.to_le_bytes());
        central.extend_from_slice(name.as_bytes());
    }
    let start = out.len();
    out.extend_from_slice(&central);
    out.extend_from_slice(b"PK\x05\x06");
    for n in [0u16,0,files.len() as u16,files.len() as u16] { out.extend_from_slice(&n.to_le_bytes()) }
    out.extend_from_slice(&(central.len() as u32).to_le_bytes());
    out.extend_from_slice(&(start as u32).to_le_bytes());
    out.extend_from_slice(&0u16.to_le_bytes());
    out
}

