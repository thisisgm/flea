#[test]
fn plugin_preview_rejects_crc_valid_chunks_with_invalid_compressed_pixels() {
    let dir = TestDir::new("plugin-preview-invalid-pixels");
    let root = dir.dir("previews");
    let work = Work::new(&root).unwrap();
    let mut bytes = PNG[..33].to_vec();
    let image = b"IDAT\0";
    bytes.extend_from_slice(&1u32.to_be_bytes());
    bytes.extend_from_slice(image);
    bytes.extend_from_slice(&crate::backend::model3d::codecs::crc32(image).to_be_bytes());
    bytes.extend_from_slice(&PNG[PNG.len() - 12..]);
    std::fs::write(work.0.join(PNG_NAME), bytes).unwrap();
    assert!(
        picture(&work.0, &root).is_err(),
        "CRC-valid chunks with invalid zlib data were published as a PNG"
    );
}

#[test]
fn plugin_preview_retention_uses_host_generation_instead_of_plugin_timestamps() {
    if crate::backend::sandboxprobe::skipped() {
        return;
    }
    let dir = TestDir::new("plugin-preview-retention");
    let root = dir.dir("previews");
    let mut kept = Vec::new();
    for i in 0..=KEPT {
        let work = Work::new(&root).unwrap();
        let input = work.0.join(PNG_NAME);
        std::fs::write(&input, PNG).unwrap();
        if i == KEPT {
            std::fs::File::options()
                .write(true)
                .open(&input)
                .unwrap()
                .set_modified(std::time::UNIX_EPOCH)
                .unwrap();
        }
        let (shown, _, _) = picture(&work.0, &root).unwrap();
        assert!(
            shown.is_file(),
            "returned preview was pruned before publication"
        );
        kept.push(shown);
    }
    assert!(!kept[0].exists());
    assert!(kept[1..].iter().all(|path| path.is_file()));
    assert_eq!(std::fs::read_dir(root.join("shown")).unwrap().count(), KEPT);
}

