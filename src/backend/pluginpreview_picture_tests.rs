#[test]
fn plugin_preview_retention_preserves_another_process_fresh_publication() {
    if crate::backend::sandboxprobe::skipped() {
        return;
    }
    let dir = TestDir::new("plugin-preview-shared-retention");
    let root = dir.path();
    for _ in 0..KEPT {
        let work = Work::new(root).unwrap();
        std::fs::write(work.0.join(PNG_NAME), PNG).unwrap();
        picture(&work.0, root).unwrap();
    }
    let files = || {
        std::fs::read_dir(root.join("shown"))
            .unwrap()
            .map(|entry| entry.unwrap().path())
            .collect::<std::collections::BTreeSet<_>>()
    };
    let before = files();
    let child = std::process::Command::new(std::env::current_exe().unwrap())
        .args([
            "--exact",
            "backend::pluginpreview::picture_tests::plugin_preview_retention_child",
        ])
        .env("FLEA_TEST_PLUGIN_PREVIEW_ROOT", root)
        .output()
        .unwrap();
    assert!(
        child.status.success(),
        "{}",
        String::from_utf8_lossy(&child.stdout)
    );
    let after = files();
    let fresh: Vec<_> = after.difference(&before).cloned().collect();
    assert_eq!(fresh.len(), 1);
    let work = Work::new(root).unwrap();
    std::fs::write(work.0.join(PNG_NAME), PNG).unwrap();
    picture(&work.0, root).unwrap();
    assert!(
        fresh[0].is_file(),
        "a new publication pruned the other process's fresh preview"
    );
    assert_eq!(files().len(), KEPT);
}

