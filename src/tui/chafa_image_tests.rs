#[test]
fn real_chafa_when_installed_stays_in_allowed_subset_in_both_color_modes() {
    if find_on(
        std::env::var_os("PATH")
            .as_deref()
            .unwrap_or(OsStr::new("")),
    )
    .is_none()
    {
        std::io::stderr()
            .write_all(b"SKIP real_chafa_when_installed: chafa is not installed on PATH\n")
            .unwrap();
        return;
    }
    if !sandboxed() {
        return;
    }
    let fixture = Fixture::new();
    for (name, bytes) in [
        ("opaque.png", OPAQUE_PNG),
        ("transparent.png", TRANSPARENT_PNG),
    ] {
        let image = fixture.file(name, bytes);
        for mode in [ColorMode::Truecolor, ColorMode::Indexed] {
            for (columns, rows) in [(1, 1), (3, 3), (7, 5)] {
                let mut job = Job::start(File::open(&image).unwrap(), columns, rows, mode)
                    .unwrap()
                    .unwrap();
                let grid = job
                    .result
                    .recv_timeout(Duration::from_secs(15))
                    .unwrap()
                    .unwrap();
                job.cancel();
                assert!(grid.columns <= columns && grid.rows <= rows && !grid.cells.is_empty());
                assert!(grid
                    .cells
                    .iter()
                    .all(|cell| matches!(cell.symbol, ' ' | '▀' | '▄')));
                if mode == ColorMode::Indexed {
                    assert!(grid.cells.iter().all(|cell| !matches!(
                        cell.foreground,
                        Color::Rgb(..)
                    ) && !matches!(
                        cell.background,
                        Color::Rgb(..)
                    )));
                }
            }
        }
    }
}

