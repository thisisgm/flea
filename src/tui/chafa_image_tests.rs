#[test]
fn captured_rgba_output_is_accepted_in_both_color_modes() {
    for (bytes, color) in [
        (TRANSPARENT_TRUECOLOR_OUTPUT, Color::Rgb(132, 24, 24)),
        (TRANSPARENT_INDEXED_OUTPUT, Color::Indexed(88)),
    ] {
        assert!(bytes.windows(4).any(|chunk| chunk == b"\x1b[7m"));
        let grid = validate(bytes, 7, 5).expect("real Chafa 1.18.3 RGBA output");
        assert_eq!((grid.columns, grid.rows), (7, 4));
        assert_eq!(
            grid.cells[14],
            Cell {
                symbol: '▀',
                foreground: color,
                background: Color::Default
            }
        );
    }
}

#[test]
fn inverse_is_normalized_and_resets_never_leak_attributes() {
    let text = "\x1b[38;5;42;48;5;17m\x1b[7m▀▄ \x1b[7m▀\x1b[27m▀\x1b[7m\x1b[0m▄\x1b[7m\x1b[m▀";
    let grid = validate(text.as_bytes(), 7, 1).unwrap();
    assert_eq!(
        grid.cells.iter().map(|c| c.symbol).collect::<String>(),
        "▄▀▀▄▀▄▀"
    );
    for at in [0, 1, 3, 4] {
        assert_eq!(grid.cells[at].foreground, Color::Indexed(42));
        assert_eq!(grid.cells[at].background, Color::Indexed(17));
    }
    assert_eq!(grid.cells[2].foreground, Color::Indexed(42));
    assert_eq!(grid.cells[2].background, Color::Indexed(42));
    for at in [5, 6] {
        assert_eq!(grid.cells[at].foreground, Color::Default);
        assert_eq!(grid.cells[at].background, Color::Default);
    }
    for bytes in [TRANSPARENT_TRUECOLOR_OUTPUT, TRANSPARENT_INDEXED_OUTPUT] {
        let mut unsafe_output = bytes.to_vec();
        unsafe_output.extend_from_slice(b"\x1b[?25l");
        assert!(validate(&unsafe_output, 7, 5).is_err());
    }
}
